// Add the expanded demo catalog once. Subsequent reloads preserve intentional removals.
export function upgradeDemoWorkspace(workspace) {
  if (workspace.catalogVersion === 2) return workspace;
  const cars = workspace.cars.map((car) => {
    const sample = initial.find((s) => s.id === car.id);
    if (!sample) return car;
    return {
      ...sample,
      ...car,
      image: car.image?.includes("images.unsplash.com")
        ? sample.image
        : car.image || sample.image,
      ownerId: car.ownerId || sample.ownerId,
      owner: car.ownerId ? car.owner : sample.owner,
      promotion: car.promotion || (car.vip ? "vip" : "standard"),
    };
  });
  for (const sample of initial)
    if (!cars.some((c) => c.id === sample.id)) cars.push(sample);
  const owners = [...workspace.owners];
  if (!owners.some((o) => o.id === "demo-fleet")) owners.push(...demoOwners);
  return { ...workspace, cars, owners, catalogVersion: 2 };
}

// Refresh only the old built-in drawings. Preserve user photos, custom listings and edits.
export function upgradeDemoPhotos(workspace) {
  return {
    ...workspace,
    cars: workspace.cars.map((car) => {
      const sample = initial.find((s) => s.id === car.id);
      if (!sample || !/^\/cars\/demo-\d+\.svg$/.test(car.image || ""))
        return car;
      return {
        ...car,
        image: sample.image,
        brand: sample.brand,
        model: sample.model,
        name: sample.name,
        type: sample.type,
        seats: sample.seats,
        description: sample.description,
      };
    }),
  };
}
